-- Politicas Usuario
CREATE POLICY "Leitura de perfis de usuarios autenticados" ON public.usuario
  FOR SELECT USING (true);

CREATE POLICY "Usuarios podem atualizar seu proprio perfil" ON public.usuario
  FOR UPDATE USING (auth.uid() = auth_user_id);

CREATE POLICY "Usuarios podem inserir seu proprio perfil" ON public.usuario
  FOR INSERT WITH CHECK (auth.uid() = auth_user_id);

-- Politicas Iniciativa
CREATE POLICY "Leitura pública de iniciativas" ON public.iniciativa
  FOR SELECT USING (true);

CREATE POLICY "Usuarios autenticados podem cadastrar iniciativas" ON public.iniciativa
  FOR INSERT WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Responsaveis podem atualizar suas iniciativas" ON public.iniciativa
  FOR UPDATE USING (
    id_usuario IN (SELECT id FROM public.usuario WHERE auth_user_id = auth.uid())
  );

